"""Table 2 (markdown) from results/metrics.csv: the same models under the three validation designs
(scan level, chemically informative regions). Writes manuscript/03b_table2.md."""
from pathlib import Path

import pandas as pd

from common import RESULTS

OUT = Path(__file__).resolve().parents[1] / "manuscript" / "03b_table2.md"
m = pd.read_csv(RESULTS / "metrics.csv")
m = m[(m.regions == "chem") & (m.level == "scan")]
info = {"random": "Random 80/20 split of scans (54 of 55 samples on both sides)",
        "holdout": "Grouped hold-out (17 test samples, 1 authentic lot)",
        "lolo": "Leave-one-lot-out (5 folds, all 55 samples)"}


def ci(r, k, nd=2, pct=False):
    f = (lambda v: f"{100 * v:.1f}") if pct else (lambda v: f"{v:.{nd}f}")
    return f"{f(r[k])} ({f(r[k + '_lo'])}–{f(r[k + '_hi'])})"


hdr = ["Validation", "RMSEP PLS (%)", "RMSEP MT-DNN (%)", "Specificity PLS-R (%)", "Specificity MT-DNN-R (%)",
       "Specificity MT-DNN class head (%)"]
lines = ["Table 2 The same models under three validation designs (scan level, chemically informative regions; "
         "cluster-bootstrap 95 % intervals over physical samples; MT-DNN means over five seeds). RMSEP is for the "
         "tahini fraction. Lot-out specificity intervals resample the five authentic samples and are indicative only "
         "(exact sample-level intervals: Table 1).", "", "| " + " | ".join(hdr) + " |", "|" + "|".join(["---"] * len(hdr)) + "|"]
for s in ("random", "holdout", "lolo"):
    r = m[m.scheme == s].set_index("model")
    if r.empty:
        continue
    lines.append("| " + " | ".join([info[s], ci(r.loc["PLS-R"], "rmsep_tahini"), ci(r.loc["MT-DNN"], "rmsep_tahini"),
                                     *[(f"{100 * r.loc[k, 'specificity']:.1f} (one authentic sample)" if s == "holdout"
                                        else ci(r.loc[k], "specificity", pct=True)) for k in ("PLS-R", "MT-DNN-R", "MT-DNN")]]) + " |")
lines += ["", "<!-- generated by src/t2_leakage.py from results/metrics.csv; do not edit by hand -->", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(OUT.read_text(encoding="utf-8"))
